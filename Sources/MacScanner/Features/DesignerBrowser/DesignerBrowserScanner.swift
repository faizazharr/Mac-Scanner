                ("Opera", "o.circle.fill", .red, "com.operasoftware.Opera", "com.operasoftware.Opera/Extensions", "com.operasoftware.Opera"),
                ("Opera GX", "gamecontroller.fill", .red, "com.operasoftware.OperaGX", "com.operasoftware.OperaGX/Extensions", "com.operasoftware.OperaGX"),
                ("Vivaldi", "v.circle.fill", .red, "Vivaldi", "Vivaldi/Default/Extensions", "Vivaldi"),
                ("Orion Browser", "sparkles.rectangle.stack.fill", .purple, "Kagi/Orion", "", "com.kagi.kagimacOS"),
                ("Apple Safari", "safari.fill", .blue, "com.apple.Safari", "", "com.apple.Safari")
            ]

            var browserResults: [BrowserInfo] = []

            for cfg in configs {
                let supportDir = appSupport.appendingPathComponent(cfg.appSupportSubpath)
                let extDir = cfg.extensionsSubpath.isEmpty ? nil : appSupport.appendingPathComponent(cfg.extensionsSubpath)
                let cacheDir = caches.appendingPathComponent(cfg.cacheSubpath)

                let isInstalled = fm.fileExists(atPath: supportDir.path) || fm.fileExists(atPath: cacheDir.path)
                guard isInstalled else { continue }

                var cacheSize: Int64 = 0
                if fm.fileExists(atPath: cacheDir.path) {
                    cacheSize = DiskScanner.size(of: cacheDir)
                }

                var extensions: [BrowserExtensionInfo] = []
                if cfg.name == "Mozilla Firefox" {
                    extensions = parseFirefoxExtensions(in: supportDir)
                } else if let extDir = extDir, fm.fileExists(atPath: extDir.path) {
                    extensions = parseChromiumExtensions(at: extDir, browserName: cfg.name)
                }

                browserResults.append(
                    BrowserInfo(
                        name: cfg.name,
                        icon: cfg.icon,
                        tintColor: cfg.tint,
                        isInstalled: true,
                        cacheBytes: cacheSize,
                        extensions: extensions,
                        cacheURL: cacheDir,
                        extensionsURL: extDir
                    )
                )
            }

            DispatchQueue.main.async { completion(browserResults) }
        }
    }

    /// Parses Firefox profile extensions.json file.
    private static func parseFirefoxExtensions(in firefoxSupportDir: URL) -> [BrowserExtensionInfo] {
        let fm = FileManager.default
        let profilesDir = firefoxSupportDir.appendingPathComponent("Profiles")
        guard let profiles = try? fm.contentsOfDirectory(at: profilesDir, includingPropertiesForKeys: [.isDirectoryKey], options: [.skipsHiddenFiles]) else {
            return []
        }

        var results: [BrowserExtensionInfo] = []
        for profile in profiles {
            let extensionsJSON = profile.appendingPathComponent("extensions.json")
            guard let data = try? Data(contentsOf: extensionsJSON),
                  let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
                  let addons = json["addons"] as? [[String: Any]] else { continue }

            for addon in addons {
                guard let id = addon["id"] as? String,
                      let active = addon["active"] as? Bool, active,
                      let defaultLocale = addon["defaultLocale"] as? [String: Any],
                      let name = defaultLocale["name"] as? String else { continue }

                let version = addon["version"] as? String ?? "1.0"
                let desc = defaultLocale["description"] as? String ?? ""
                let isHeavy = isPotentialHeavyExtension(name: name, desc: desc)

                results.append(
                    BrowserExtensionInfo(
                        extensionID: id,
                        name: name,
                        version: version,
                        description: desc,
                        browserName: "Mozilla Firefox",
                        isHeavyCandidate: isHeavy
                    )
                )
            }
        }
        return results
    }

    /// Parses Chromium extension directories and reads manifest.json metadata for readable names.
    private static func parseChromiumExtensions(at url: URL, browserName: String) -> [BrowserExtensionInfo] {
        let fm = FileManager.default
        guard let extFolders = try? fm.contentsOfDirectory(at: url, includingPropertiesForKeys: [.isDirectoryKey], options: [.skipsHiddenFiles]) else {
            return []
        }

        var results: [BrowserExtensionInfo] = []

        for folder in extFolders {
            let extensionID = folder.lastPathComponent
            // Extension folder usually contains version folders (e.g. "1.4.2_0")
            guard let versionFolders = try? fm.contentsOfDirectory(at: folder, includingPropertiesForKeys: [.isDirectoryKey], options: [.skipsHiddenFiles]),
                  let latestVersion = versionFolders.first else {
                continue
            }

            let manifestURL = latestVersion.appendingPathComponent("manifest.json")
            guard let data = try? Data(contentsOf: manifestURL),
                  let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else {
                continue
            }

            var name = json["name"] as? String ?? extensionID
            let version = json["version"] as? String ?? "1.0"
            var desc = json["description"] as? String ?? "Browser extension"

            // Localized Chrome message name lookup (e.g. "__MSG_appName__")
            if name.hasPrefix("__MSG_") {
                name = resolveLocalizedName(in: latestVersion, rawKey: name) ?? extensionID
            }
            if desc.hasPrefix("__MSG_") {
                desc = resolveLocalizedName(in: latestVersion, rawKey: desc) ?? desc
            }

            let isHeavy = isPotentialHeavyExtension(name: name, desc: desc)

            results.append(
                BrowserExtensionInfo(
                    extensionID: extensionID,
                    name: name,
                    version: version,
                    description: desc,
                    browserName: browserName,
                    isHeavyCandidate: isHeavy
                )
            )
        }

        return results.sorted { $0.name.lowercased() < $1.name.lowercased() }
    }

    private static func resolveLocalizedName(in versionFolder: URL, rawKey: String) -> String? {
        let key = rawKey
            .replacingOccurrences(of: "__MSG_", with: "")
            .replacingOccurrences(of: "__", with: "")

        let fm = FileManager.default
        let locales = ["en", "en_US", "en_GB", "id", "default"]
        for loc in locales {
            let msgFile = versionFolder.appendingPathComponent("_locales/\(loc)/messages.json")
            if fm.fileExists(atPath: msgFile.path),
               let data = try? Data(contentsOf: msgFile),
               let json = try? JSONSerialization.jsonObject(with: data) as? [String: [String: Any]],
               let item = json[key] ?? json[key.lowercased()],
               let message = item["message"] as? String {
                return message
            }
        }
        return nil
    }

    private static func isPotentialHeavyExtension(name: String, desc: String) -> Bool {
        let text = (name + " " + desc).lowercased()
        let heavyKeywords = [
            "record", "screen", "capture", "video", "download", "ai", "copilot",
            "chatgpt", "inspector", "debug", "adblock", "ublock", "grammarly",
            "vpn", "proxy", "translate", "scraper", "fitt"
        ]
        return heavyKeywords.contains { text.contains($0) }
    }

    // MARK: - Plain Language Diagnostics

    static func generatePlainLanguageInsights(
        designCaches: [DesignAppCacheInfo],
        browsers: [BrowserInfo],
        heaviestApps: [ProcessStats]
    ) -> [DesignerDiagnosticInsight] {
        var insights: [DesignerDiagnosticInsight] = []

        // 1. Creative Apps Memory & Cache Insights
        let totalDesignCache = designCaches.reduce(0) { $0 + $1.sizeBytes }
        if totalDesignCache > 5 * 1024 * 1024 * 1024 { // > 5 GB
            insights.append(
                DesignerDiagnosticInsight(
                    title: "Oversized Design & Media Caches",
                    summary: "\(ByteFormat.string(totalDesignCache)) of creative app cache is occupying disk space.",
                    explanation: "Apps like Adobe Premiere, After Effects, and Figma cache render preview frames and canvas data. Cleaning this cache is safe and immediately reclaims storage.",
                    icon: "paintbrush.pointed.fill",
                    color: .purple,
                    actionTitle: "Clean Design Caches",
                    targetURL: designCaches.first?.path
                )
            )
        }

        // 2. Heavy Browsers & Extensions
        for browser in browsers {
            if browser.extensionsCount >= 6 {
                insights.append(
                    DesignerDiagnosticInsight(
                        title: "\(browser.name) Has \(browser.extensionsCount) Active Extensions",
                        summary: "Numerous browser extensions inject scripts into every open tab, consuming memory.",
                        explanation: "Each browser extension adds background processing. Disabling unused extensions improves browser speed and reduces memory usage.",
                        icon: browser.icon,
                        color: browser.tintColor,
                        actionTitle: "Manage Extensions in \(browser.name)",
                        targetURL: browser.extensionsURL,
                        browserName: browser.name
                    )
                )
            }

            if browser.cacheBytes > 3 * 1024 * 1024 * 1024 { // > 3 GB
                insights.append(
                    DesignerDiagnosticInsight(
                        title: "\(browser.name) Web Cache Reached \(ByteFormat.string(browser.cacheBytes))",
                        summary: "Cached media, high-resolution images, and scripts have accumulated.",
                        explanation: "Clearing web cache frees up storage without deleting your passwords, logins, or bookmarks.",
                        icon: "globe",
                        color: browser.tintColor,
                        actionTitle: "Clear Web Cache",
                        targetURL: browser.cacheURL
                    )
                )
            }
        }

        // 3. Figma / Adobe Heavy Process Diagnostic
        let creativeAppNames = ["figma", "photoshop", "illustrator", "premiere", "after effects", "blender", "sketch", "resolve"]
        let runningCreative = heaviestApps.filter { proc in
            creativeAppNames.contains { proc.name.lowercased().contains($0) }
        }

        if let heaviest = runningCreative.max(by: { $0.memoryBytes < $1.memoryBytes }), heaviest.memoryBytes > 2 * 1024 * 1024 * 1024 {
            insights.append(
                DesignerDiagnosticInsight(
                    title: "\(heaviest.name) High Memory Usage (\(ByteFormat.string(heaviest.memoryBytes)))",
                    summary: "Open vector canvases or media projects are utilizing substantial RAM.",
                    explanation: "If zooming or panning feels sluggish, consider closing inactive project tabs or restarting the app to release memory.",
                    icon: "memorychip.fill",
                    color: .orange,
                    actionTitle: nil,
                    targetURL: nil
                )
            )
        }

        if insights.isEmpty {
            insights.append(
                DesignerDiagnosticInsight(
                    title: "Design & Browser Workspaces Optimal",
                    summary: "No excessive cache accumulation or heavy background extensions detected.",
                    explanation: "Your creative design apps and web browsers are running efficiently.",
                    icon: "checkmark.seal.fill",
                    color: .green,
                    actionTitle: nil,
                    targetURL: nil
                )
            )
        }

        return insights
    }

    /// Opens the official in-browser Extension Management page (chrome://extensions/, arc://extensions/, etc.)
    /// directly in the browser so the user can easily toggle off or remove extensions with 1 click.
    @MainActor
    static func openBrowserExtensionPage(browserName: String) {
        let lower = browserName.lowercased()
        if lower.contains("chrome") {
            _ = Shell.run("/usr/bin/open", ["-a", "Google Chrome", "chrome://extensions/"])
            ToastManager.shared.show("Opening extensions page in Google Chrome", icon: "puzzlepiece.extension.fill", tint: .blue)
        } else if lower.contains("arc") {
            _ = Shell.run("/usr/bin/open", ["-a", "Arc", "arc://extensions/"])
            ToastManager.shared.show("Opening extensions page in Arc", icon: "puzzlepiece.extension.fill", tint: .purple)
        } else if lower.contains("brave") {
            _ = Shell.run("/usr/bin/open", ["-a", "Brave Browser", "brave://extensions/"])
            ToastManager.shared.show("Opening extensions page in Brave", icon: "puzzlepiece.extension.fill", tint: .orange)
        } else if lower.contains("edge") {
            _ = Shell.run("/usr/bin/open", ["-a", "Microsoft Edge", "edge://extensions/"])
            ToastManager.shared.show("Opening extensions page in Microsoft Edge", icon: "puzzlepiece.extension.fill", tint: .cyan)
        } else if lower.contains("firefox") {
            _ = Shell.run("/usr/bin/open", ["-a", "Firefox", "about:addons"])
            ToastManager.shared.show("Opening add-ons page in Firefox", icon: "puzzlepiece.extension.fill", tint: .red)
        } else {
            _ = Shell.run("/usr/bin/open", ["https://support.apple.com/guide/safari/safari-extensions-sfri32508/mac"])
        }
    }
