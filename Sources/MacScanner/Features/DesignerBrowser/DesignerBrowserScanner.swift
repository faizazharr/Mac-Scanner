    static func scanDesignCaches(completion: @escaping ([DesignAppCacheInfo]) -> Void) {
        DispatchQueue.global(qos: .userInitiated).async {
            let fm = FileManager.default
            let list = candidateDesignCaches()
            var results: [DesignAppCacheInfo] = []

            for var item in list {
                var isDir: ObjCBool = false
                if fm.fileExists(atPath: item.path.path, isDirectory: &isDir) {
                    item.exists = true
                    item.sizeBytes = DiskScanner.size(of: item.path)
                    if item.sizeBytes > 1024 * 1024 { // at least 1MB to be notable
                        results.append(item)
                    }
                }
            }

            results.sort { $0.sizeBytes > $1.sizeBytes }
            DispatchQueue.main.async { completion(results) }
        }
    }

